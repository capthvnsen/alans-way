// Real Chromium permission requests, full app Settings, isolated temporary profile.
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), http = require('node:http');
const { app, BrowserWindow, webContents, session, dialog } = require('electron');
const profile = process.env.HERMES_TEST_PROFILE || fs.mkdtempSync(path.join(os.tmpdir(), 'workspace-permissions-'));
const { prepareFixture, quitFixture } = require('./electron-fixture.cjs');
prepareFixture(profile);
fs.writeFileSync(path.join(profile, 'preferences.json'), JSON.stringify({preview:false}));
let prompts = 0; dialog.showMessageBox = async () => { prompts++; return {response:0}; };
require('../src/main.cjs');
const until = async (read, predicate) => { for (let i = 0; i < 200; i++) { const value = await read(); if (predicate(value)) return value; await new Promise(r => setTimeout(r, 30)); } throw new Error('Permission fixture timed out.'); };
let server;
app.whenReady().then(async () => {
  const win = await until(() => BrowserWindow.getAllWindows()[0], Boolean);
  const telegram = webContents.getAllWebContents().find(wc => wc.session === session.fromPartition('persist:telegram'));
  telegram.stop(); await telegram.loadURL('about:blank');
  const evaluate = code => win.webContents.executeJavaScript(code);
  await until(() => evaluate('typeof window.workspace').catch(() => ''), value => value === 'object');
  const invoke = (name, value = {}) => evaluate(`window.workspace.command(${JSON.stringify(name)},${JSON.stringify(value)})`);
  server = http.createServer((_req, res) => res.end('<title>Location permission fixture</title><p>Local location test</p>'));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const tab = await invoke('create-tab', {url:origin});
  const browser = await until(() => webContents.getAllWebContents().find(wc => wc.getURL() === origin + '/'), Boolean);
  await until(() => browser.isLoading(), value => !value);
  const request = () => browser.executeJavaScript('new Promise(resolve => navigator.geolocation.getCurrentPosition(() => resolve(0), e => resolve(e.code), {timeout:1500}))');
  assert.equal(await request(), 1); assert.equal(await request(), 1); assert.equal(prompts, 0);
  await invoke('settings', {locationDefault:'ask'});
  assert.equal(await request(), 1); assert.equal(prompts, 1);
  browser.reload(); await until(() => browser.isLoading(), value => !value);
  assert.equal(await request(), 1); assert.equal(prompts, 1);
  assert.equal(JSON.parse(fs.readFileSync(path.join(profile,'preferences.json'))).sitePermissions.browser[origin].geolocation, 'block');
  await evaluate('document.getElementById("settings-button").click()');
  await evaluate('document.getElementById("settings-category-browser").click()');
  assert.equal(await evaluate('document.getElementById("permission-origin").placeholder'), 'https://www.google.com');
  assert.equal(await until(() => evaluate(`document.querySelector('#site-permissions select')?.value`), Boolean), 'block');
  await evaluate(`(() => {
    const frame = window.requestAnimationFrame;
    window.__fixtureFrame = frame;
    window.requestAnimationFrame = callback => frame(() => setTimeout(callback, 250));
    document.getElementById("modal-close").click();
  })()`);
  await evaluate(`new Promise(resolve => requestAnimationFrame(resolve)).then(() => {
    window.requestAnimationFrame = window.__fixtureFrame;
    delete window.__fixtureFrame;
  })`);
  await invoke('set-site-permission', {origin, permission:'geolocation', decision:'allow'});
  assert.equal(await browser.executeJavaScript('navigator.permissions.query({name:"geolocation"}).then(p => p.state)'), 'granted');
  await invoke('control', {id:tab.id, controller:'agent'});
  assert.notEqual(await browser.executeJavaScript('navigator.permissions.query({name:"geolocation"}).then(p => p.state)'), 'granted');
  await invoke('control', {id:tab.id, controller:'human'});
  await invoke('set-site-permission', {origin, permission:'geolocation', decision:'block'});
  assert.equal(await request(), 1);
  console.log('PASS: actual Chromium repeat location requests, remembered denial across reload, persisted preferences, Settings UI, per-site grant/revoke and agent takeover denial.');
  console.log('Runtime:', JSON.stringify({electron:process.versions.electron, chromium:process.versions.chrome, prompts}));
  quitFixture(server);
}).catch(error => { console.error(error.stack); server?.close(); app.exit(1); });
